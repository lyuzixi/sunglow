const I18N = { zh: null, zhHant: I18N_ZH_HANT, en: I18N_EN };

function langInfo(k) {
  for (let i = 0; i < LANGS.length; i++) if (LANGS[i].k === k) return LANGS[i];
  return LANGS[0];
}
/* 取词。`vars` 用 {name} 占位 —— 拼中文时用「·」「：」，拼英文时该用 ", " ": "，
   所以句子里凡是有标点的地方都做成整句模板 + 参数，而不是把中文标点拼进英文。 */
function i18n(zh, vars) {
  const d = I18N[LANG];
  let s = (d && Object.prototype.hasOwnProperty.call(d, zh)) ? d[zh] : zh;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined || vars[k] === null) ? "" : String(vars[k]));
  return s;
}
/* 语言识别：URL 参数 > 偏好存储 > 浏览器语言 > 简体。
   之所以把 URL 放在最前：分享链接要能固定语言（与 lat/lon/date 同一套约定）。 */
function detectLang() {
  let k = null;
  try {
    const p = new URLSearchParams(location.search || "");
    k = p.get("lang");
  } catch (e) { /* 无 URL 环境，忽略 */ }
  if (!k && typeof prefRead === "function") {
    try { const pr = prefRead(); if (pr && pr.lang) k = pr.lang; } catch (e) { }
  }
  if (!k && navigator.languages && navigator.languages.length) k = navigator.languages[0];
  else if (!k) k = navigator.language || "";
  return normalizeLang(k);
}
function normalizeLang(raw) {
  const s = String(raw || "").toLowerCase();
  if (!s) return "zh";
  /* 繁体：zh-TW / zh-HK / zh-MO / zh-Hant*，以及显式写的 zh-hant */
  if (/^zh[-_]?(hant|tw|hk|mo)/.test(s) || s === "zh-hant") return "zhHant";
  if (/^zh/.test(s)) return "zh";
  if (/^en/.test(s)) return "en";
  return "zh";
}
/* 切换语言：写 <html lang>、刷新静态 DOM、重渲所有动态区域。
   `relang` 定义在 _p6.js（地图 UI 也在这里刷新）—— 用 typeof 探测而不是直接调用，
   免得"没加载到那里"就抛错。 */
function setLang(k, silent) {
  const info = langInfo(k);
  LANG = info.k;
  try { document.documentElement.lang = info.htmllang; } catch (e) { }
  applyI18nDom(document);
  if (!silent && typeof relang === "function") { try { relang(); } catch (e) { softWarn("语言切换后重渲染失败", e); } }
  return LANG;
}
/* 静态文案：模板里带 data-i18n 的元素按属性改写。
   四种位置各管一种：文本 / placeholder / aria-label / title。 */
function applyI18nDom(root) {
  const sc = root || document;
  const each = (sel, attr, key) => {
    const list = sc.querySelectorAll("[" + sel + "]");
    for (let i = 0; i < list.length; i++) {
      const el = list[i];
      const v = i18n(el.getAttribute(sel));
      if (attr === "text") el.textContent = v; else el.setAttribute(attr, v);
    }
  };
  each("data-i18n", "text");
  each("data-i18n-ph", "placeholder");
  each("data-i18n-aria", "aria-label");
  each("data-i18n-title", "title");
}
/* 可信度文案（唯一入口）：ENS_CONF_BANDS 只存中文键与阈值（约束 25），
   展示层在这里过一遍 i18n —— 四个使用点（徽标 / 模型卡 / 因素表 / 悬停卡）
   都走它，避免在四处各写一遍 i18n(cf.txt)。 */
function confText(cf) {
  return {
    lv: i18n(cf.lv), txt: i18n(cf.txt), hint: i18n(cf.hint),
    color: cf.color, bg: cf.bg, bd: cf.bd, key: cf.key
  };
}
